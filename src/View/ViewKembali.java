private void ViewDataKembali() {
    DefaultTableModel tpeg = new DefaultTableModel();
    
    tpeg.addColumn("no_pinjam");
    tpeg.addColumn("tanggal_pinjam");    
    tpeg.addColumn("id_user");
    tpeg.addColumn("kode_buku");
    tpeg.addColumn("tanggal_kembali");
    tpeg.addColumn("status");


    Connection connn = null;
    Statement stat = null;
    ResultSet rs = null;

    try {
        connn = Conection.Connection.getConnection();
        String sql = "SELECT * FROM tb_peminjaman";
        stat = connn.createStatement();
        rs = stat.executeQuery(sql);

        while (rs.next()) {
            tpeg.addRow(new Object[]{
            rs.getString(1),
            rs.getString(2),
            rs.getString(3),
            rs.getString(4),
            rs.getString(5),
            rs.getString(6)});
        }

        TablePengembalian.setModel(tpeg);
    } catch (SQLException e) {
        System.out.println("Error: " + e.getMessage());
    } finally {
        // Pastikan untuk menutup ResultSet, Statement, dan Connection
        if (rs != null) {
            try {
                rs.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
        if (stat != null) {
            try {
                stat.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
        if (connn != null) {
            try {
                connn.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }
}

public int hitungDenda(String tanggalPinjam, String tanggalKembali){
    LocalDate tglKembali = LocalDate.parse(tanggalKembali);
    LocalDate tglPinjam = LocalDate.parse(tanggalPinjam);

    long selisihHari = ChronoUnit.DAYS.between(tglKembali, tglPinjam);

    if (selisihHari > 30){
        return (int) ((selisihHari - 30) * 5000); 
    } else{
        return 0;   
    }
}

