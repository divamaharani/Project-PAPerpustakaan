    private void TablePengembalianMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TablePengembalianMouseClicked
        int baris = TablePengembalian.getSelectedRow();
        if (baris < 20){
            NopinjamTFK.setText(TablePengembalian.getValueAt(baris,0).toString());
            StatusTFK.setText(TablePengembalian.getValueAt(baris,5).toString());
            TanggalkembaliTFK.setText(TablePengembalian.getValueAt(baris,4).toString());
        }
        
        String tglKembali = TablePengembalian.getValueAt(baris,4).toString();
        String tglPinjam = TablePengembalian.getValueAt(baris,1).toString();
        hitungDenda(tglKembali, tglPinjam);
        TotalDendaTF.setText(String.valueOf(hitungDenda(tglKembali, tglPinjam)));
    }//GEN-LAST:event_TablePengembalianMouseClicked

