private void ViewDataUser(){
    DefaultTableModel tpeg = new DefaultTableModel();
    tpeg.addColumn("id_user");
    tpeg.addColumn("password_user");
    tpeg.addColumn("nama_user");
    tpeg.addColumn("jenis_kelamin_user");
    tpeg.addColumn("no_hp_user");
    tpeg.addColumn("email_user");
    tpeg.addColumn("alamat_user");
    tpeg.addColumn("tanggal_lahir_user");
    tpeg.addColumn("role");
    
    
    try {
        Connection con = Conection.Connection.getConnection();
        String sql = "Select * from tb_user";
        Statement stat = con.createStatement();
        ResultSet rs = stat.executeQuery(sql);
        while (rs.next()){
            tpeg.addRow(new Object[]{
            rs.getString(1),
            rs.getString(2),
            rs.getString(3),
            rs.getString(4),
            rs.getString(5),
            rs.getString(6),
            rs.getString(7),
            rs.getDate(8),
            rs.getString(9)});
        }
        TableUser.setModel(tpeg);
    } catch (SQLException e) {
        System.out.println("Error");
    }    
}

