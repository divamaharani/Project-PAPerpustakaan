    private void TableUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableUserMouseClicked
        int baris = TableUser.getSelectedRow();
        if (baris < 20){
            IDUserTF.setText(TableUser.getValueAt(baris,0).toString());
            PasswordUserTF.setText(TableUser.getValueAt(baris,1).toString());
            NamaUserTF.setText(TableUser.getValueAt(baris,2).toString());
            JenisKelaminCB.setSelectedItem(TableUser.getValueAt(baris,3).toString());
            NoHpTF.setText(TableUser.getValueAt(baris,4).toString());
            EmailTF.setText(TableUser.getValueAt(baris,5).toString());
            AlamatTF.setText(TableUser.getValueAt(baris,6).toString());
            TglLahirTF.setText(TableUser.getValueAt(baris,7).toString());
            RoleCB.setSelectedItem(TableUser.getValueAt(baris,8).toString());
        }
        IDUserTF.disable();
        BtnTambah.setEnabled(false);
        BtnReset.setEnabled(true);
        BtnDelete.setEnabled(true);
        BtnUpdate.setEnabled(true);
    }//GEN-LAST:event_TableUserMouseClicked

    private void BtnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnTambahActionPerformed
        try {
            ModelUserData tb = new ModelUserData();
            tb.setId_user(IDUserTF.getText());
            tb.setPassword(PasswordUserTF.getText());
            tb.setNama_user(NamaUserTF.getText());
            tb.setJenis_kelamin_user(JenisKelaminCB.getSelectedItem().toString());
            tb.setNo_hp_user(NoHpTF.getText());
            tb.setEmail_user(EmailTF.getText());
            tb.setAlamat_user(AlamatTF.getText());
            tb.setTanggal_lahir_user(TglLahirTF.getText());
            tb.setRole(RoleCB.getSelectedItem().toString());
        
        if (IDUserTF.getText().equals("") || PasswordUserTF.getText().equals("") || NamaUserTF.getText().equals("")||
                JenisKelaminCB.getSelectedItem().equals("") || NoHpTF.getText().equals("") || EmailTF.getText().equals("")||
                AlamatTF.getText().equals("") || TglLahirTF.getText().equals("") || RoleCB.getSelectedItem().equals("")) {
                JOptionPane.showMessageDialog(null, "Data tidak boleh kosong!", "Warning", JOptionPane.WARNING_MESSAGE);            
        } else {
            ControlUserData u = new ControlUserData();
            u.tambah(tb);
            Reset();
            ViewDataUser();
        }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal koneksi untuk simpan"+e, "Warning", JOptionPane.WARNING_MESSAGE);
            
        }
    }//GEN-LAST:event_BtnTambahActionPerformed

